      _values[language]![key] ?? _obligationValues[language]![key] ?? key;
  String format(String key, Map<String, Object> values) {
    var value = text(key);
    for (final entry in values.entries) {
      value = value.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return value;
  }

